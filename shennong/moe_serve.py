"""MoE-of-LoRAs inference: route the question, load the matching expert adapter, answer.

One base GGUF (~940 MB) plus one small adapter per domain. The router (a trained classifier) picks the expert;
the *weights in use* change per query. If an adapter has not been trained yet the answer falls back to the
dense base and says so — the demo never pretends to be an MoE it does not have.

    adapters live at artifacts/adapters/{t1_classical,t2_natprod,safety}.gguf
    convert with: python convert_lora_to_gguf.py <adapter_dir> --outfile ... --outtype q8_0
"""
from __future__ import annotations

import os
import pathlib
import time

ROOT = pathlib.Path(__file__).resolve().parent.parent
ADAPTERS = ROOT / "artifacts" / "adapters"
DECODE = {"temperature": 0.2, "top_p": 0.9, "seed": 1337}
_LLMS: dict[str, object] = {}


def _base_gguf() -> pathlib.Path | None:
    from shennong.answer import _GGUF_CANDIDATES  # noqa: PLC0415
    return next((p for p in _GGUF_CANDIDATES if p.exists()), None)


def adapters_present() -> dict[str, bool]:
    return {d: (ADAPTERS / f"{d}.gguf").exists() for d in ("t1_classical", "t2_natprod", "safety")}


def _load(domain: str):
    """A Llama instance for the base + this domain's adapter (cached)."""
    if domain in _LLMS:
        return _LLMS[domain]
    base = _base_gguf()
    if base is None:
        return None
    from llama_cpp import Llama
    adapter = ADAPTERS / f"{domain}.gguf"
    kw = dict(model_path=str(base), n_ctx=1024, n_threads=4, verbose=False)
    if adapter.exists():
        kw["lora_path"] = str(adapter)
    try:
        llm = Llama(**kw)
    except Exception:  # noqa: BLE001 — a bad adapter must not take the demo down
        kw.pop("lora_path", None)
        llm = Llama(**kw)
    _LLMS[domain] = llm
    return llm


def answer_moe(question: str, max_new_tokens: int = 40) -> dict:
    """Route -> expert -> answer. Returns which weights answered, and the router's probabilities."""
    from shennong.router import route
    from shennong.safety.screen import screen

    q = (question or "").strip()
    if not q:
        return {"ok": False, "error": "empty question"}
    safety = screen(q)
    if not safety.allowed:
        cats = {r.get("category") for r in safety.reasons}
        if cats & {"dual_use", "medical", "toxin_synthesis", "self_treatment"}:
            return {"ok": False, "blocked": True,
                    "reason": "; ".join(r.get("detail", "") for r in safety.reasons)}

    routed = route(q)
    domain = routed.get("expert") if routed.get("ok") else None
    llm = _load(domain) if domain else None
    used = domain if (llm is not None and (ADAPTERS / f"{domain}.gguf").exists()) else "dense-1.5b"
    if llm is None:
        from shennong.answer import answer_direct
        out = answer_direct(q, max_new_tokens=max_new_tokens)
        out["router"] = routed
        out["answered_by"] = "dense-1.5b"
        return out

    prompt = f"<|user|>{q}<|assistant|>"
    t0 = time.time()
    r = llm(prompt, max_tokens=max_new_tokens, temperature=DECODE["temperature"],
            top_p=DECODE["top_p"], seed=DECODE["seed"])
    return {
        "ok": True, "question": q,
        "answer": (r["choices"][0]["text"] or "").strip(),
        "prompt": prompt,
        "router": routed,
        "answered_by": used,
        "expert_label": (routed.get("ranked") or [{}])[0].get("label", ""),
        "model": {"checkpoint": f"base + {used} adapter (MoE-of-LoRAs)" if used != "dense-1.5b"
                  else "dense fine-tuned 1.5B", "params": 1543714304},
        "decode": {**DECODE, "max_tokens": max_new_tokens},
        "latency_ms": int((time.time() - t0) * 1000),
        "note": "Routed to an expert adapter; the answer is generated by the model weights, not a rule table.",
    }
